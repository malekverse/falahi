CREATE OR REPLACE FUNCTION compute_platform_price()
RETURNS TRIGGER AS $$
BEGIN
  NEW.platform_price_millimes := ROUND(NEW.asking_price_millimes * 1.12);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_platform_price ON inventory_items;
CREATE TRIGGER trg_platform_price
  BEFORE INSERT OR UPDATE OF asking_price_millimes ON inventory_items
  FOR EACH ROW EXECUTE FUNCTION compute_platform_price();

