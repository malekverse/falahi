CREATE OR REPLACE FUNCTION validate_pickup_otp(trip_id UUID, otp_input TEXT)
RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_trip trips%ROWTYPE;
BEGIN
  SELECT * INTO v_trip FROM trips WHERE id = trip_id FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'error', 'trip_not_found');
  END IF;

  IF v_trip.status != 'accepted' THEN
    RETURN jsonb_build_object('success', false, 'error', 'invalid_status');
  END IF;

  IF v_trip.otp_pickup != otp_input THEN
    RETURN jsonb_build_object('success', false, 'error', 'invalid_otp');
  END IF;

  UPDATE trips SET status = 'in_transit', picked_up_at = NOW() WHERE id = trip_id;

  RETURN jsonb_build_object('success', true);
END;
$$;

CREATE OR REPLACE FUNCTION validate_delivery_otp(trip_id UUID, otp_input TEXT)
RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_trip trips%ROWTYPE;
BEGIN
  SELECT * INTO v_trip FROM trips WHERE id = trip_id FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'error', 'trip_not_found');
  END IF;

  IF v_trip.status NOT IN ('in_transit', 'arrived_hub') THEN
    RETURN jsonb_build_object('success', false, 'error', 'invalid_status');
  END IF;

  IF v_trip.otp_delivery != otp_input THEN
    RETURN jsonb_build_object('success', false, 'error', 'invalid_otp');
  END IF;

  UPDATE trips SET
    status = 'delivered',
    delivered_at = NOW()
  WHERE id = trip_id;

  RETURN jsonb_build_object('success', true);
END;
$$;

